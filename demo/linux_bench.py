#!/usr/bin/env python3
"""Benchmark the installed daemon and real picker reloads; prints JSON.

python3 demo/linux_bench.py --samples 25
Warm-cache results, serial requests, no concurrent load generated by this script.
"""
import argparse
import json
import math
import os
from pathlib import Path
import socket
import statistics
import tempfile
import subprocess
import time

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--samples", type=int, default=25)
parser.add_argument("--restart", action="store_true", help="also measure five warm-disk service starts; requires cached sudo")
args = parser.parse_args()
if args.samples < 5:
    parser.error("at least five samples are needed")
root = Path(__file__).resolve().parents[1]
home = Path.home()
data = Path(os.environ.get("XDG_DATA_HOME", home / ".local/share")) / "fsearch"


def stats(samples):
    ordered = sorted(samples)
    return {"p50_ms": round(statistics.median(ordered), 3),
            "p95_ms": round(ordered[math.ceil(len(ordered) * .95) - 1], 3),
            "samples": len(ordered)}

def memory():
    pid = subprocess.check_output(["systemctl", "show", f"fsearch-{os.getuid()}.service", "-p", "MainPID", "--value"], text=True).strip()
    fields = {"VmRSS", "RssAnon", "RssFile", "VmHWM", "VmSwap"}
    return {line.split(":")[0] + "_KiB": int(line.split()[1])
            for line in Path(f"/proc/{pid}/status").read_text().splitlines()
            if line.split(":")[0] in fields}


with socket.socket(socket.AF_UNIX) as conn:
    conn.settimeout(120)
    conn.connect(str(data / "fsearch.sock"))
    with conn.makefile("rwb") as stream:
        def request(value):
            start = time.perf_counter_ns()
            stream.write(json.dumps(value).encode() + b"\n")
            stream.flush()
            result = json.loads(stream.readline())
            elapsed = (time.perf_counter_ns() - start) / 1_000_000
            if not result.get("ok"):
                raise RuntimeError(result)
            return elapsed, result

        _, status = request({"op": "status"})
        if status["content_pending"]:
            raise RuntimeError("wait for content_pending=0 before benchmarking")
        workloads = {
            "global_fuzzy": {"q": "fsearch main", "limit": 50},
            "global_common_name": {"q": "readme", "limit": 50},
            "scoped_name": {"q": "main", "in": str(root / "src"), "limit": 50},
            "scoped_typo": {"q": "egnine.rs", "in": str(root / "src"), "limit": 50},
            "global_newest": {"q": "", "sort": "modified-desc", "limit": 200},
            "global_oldest": {"q": "", "sort": "modified-asc", "limit": 200},
            "global_name_sort": {"q": "", "sort": "name", "limit": 200},
            "global_type_sort": {"q": "", "sort": "type", "limit": 200},
            "global_size_sort": {"q": "", "sort": "size-desc", "limit": 200},
            "scoped_content": {"op": "grep", "pattern": "apply_dir", "in": str(root / "src"), "limit": 50},
            "global_content": {"op": "grep", "pattern": "apply_dir", "limit": 50},
            "scoped_regex": {"op": "grep", "mode": "regex", "pattern": r"fn\s+(apply|search)\w*", "in": str(root / "src"), "limit": 50},
            "scoped_symbol": {"op": "grep", "mode": "symbol", "pattern": "apply_dir", "in": str(root / "src"), "limit": 50},
        }
        results = {}
        for name, value in workloads.items():
            _, example = request(value)
            if name == "scoped_typo" and str(root / "src/engine.rs") not in {h["path"] for h in example["hits"]}:
                raise RuntimeError("typo workload did not find engine.rs")
            samples = [request(value)[0] for _ in range(args.samples)]
            results[name] = stats(samples)
            results[name]["returned"] = len(example.get("hits", example.get("files", [])))
            if "complete" in example:
                results[name].update({k: example[k] for k in ("complete", "source", "read", "candidates")})
        samples = []
        for _ in range(args.samples):
            for query in ("m", "ma", "mai", "main", "", "e", "en", "eng", "engin", "engine"):
                samples.append(request({"q": query, "in": str(root / "src"), "limit": 50})[0])
        results["typing_sequence"] = stats(samples)
        warm_memory = memory()
        with tempfile.TemporaryDirectory(prefix=".fsearch-bench-", dir=home) as directory:
            original = Path(directory) / "live.txt"
            renamed = Path(directory) / "renamed.txt"
            probe = {"q": "", "in": directory, "limit": 50}

            def await_paths(expected):
                deadline = time.monotonic() + 30
                while time.monotonic() < deadline:
                    if {h["path"] for h in request(probe)[1]["hits"]} == expected:
                        return
                    time.sleep(.005)
                raise RuntimeError("live update did not converge")

            live = {name: [] for name in ("live_create", "live_rename", "live_delete")}
            for _ in range(args.samples):
                start = time.perf_counter_ns()
                original.write_text("FSearch benchmark live update\n")
                await_paths({str(original)})
                live["live_create"].append((time.perf_counter_ns() - start) / 1_000_000)
                start = time.perf_counter_ns()
                original.rename(renamed)
                await_paths({str(renamed)})
                live["live_rename"].append((time.perf_counter_ns() - start) / 1_000_000)
                start = time.perf_counter_ns()
                renamed.unlink()
                await_paths(set())
                live["live_delete"].append((time.perf_counter_ns() - start) / 1_000_000)
            results.update({name: stats(samples) for name, samples in live.items()})
        _, end_status = request({"op": "status"})

picker = home / ".local/bin/fsearch-desktop"
for label, query in (("picker_reload", f"main in:{root / 'src'}"), ("picker_reload_200", "readme")):
    command = [str(picker), "--results", "--query", query, "--sort", "relevance", "--width", "120"]
    subprocess.run(command, stdout=subprocess.DEVNULL, check=True)
    reloads = []
    for _ in range(args.samples):
        start = time.perf_counter_ns()
        subprocess.run(command, stdout=subprocess.DEVNULL, check=True)
        reloads.append((time.perf_counter_ns() - start) / 1_000_000)
    results[label] = stats(reloads)

if args.restart:
    service = f"fsearch-{os.getuid()}.service"
    first_answers, reconciliations = [], []
    for _ in range(5):
        subprocess.run(["sudo", "-n", "systemctl", "stop", service], check=True)
        snapshot = (data / "index.bin").stat().st_mtime_ns
        start = time.perf_counter_ns()
        try:
            subprocess.run(["sudo", "-n", "systemctl", "start", service], check=True)
            deadline = time.monotonic() + 120
            while time.monotonic() < deadline:
                try:
                    with socket.socket(socket.AF_UNIX) as conn:
                        conn.settimeout(30)
                        conn.connect(str(data / "fsearch.sock"))
                        conn.sendall(json.dumps({"q": "main", "in": str(root / "src"), "limit": 50}).encode() + b"\n")
                        with conn.makefile("rb") as stream:
                            answer = json.loads(stream.readline())
                    if answer.get("ok") and str(root / "src/main.rs") in {h["path"] for h in answer["hits"]}:
                        break
                except OSError:
                    pass
                time.sleep(.005)
            else:
                raise RuntimeError("service did not answer the known filename query")
            first_answers.append((time.perf_counter_ns() - start) / 1_000_000)
            while (data / "index.bin").stat().st_mtime_ns == snapshot:
                if time.monotonic() >= deadline:
                    raise RuntimeError("startup reconciliation did not publish its snapshot")
                time.sleep(.01)
            reconciliations.append((time.perf_counter_ns() - start) / 1_000_000)
        finally:
            subprocess.run(["sudo", "-n", "systemctl", "start", service], check=True)
    results["warm_service_first_answer"] = stats(first_answers)
    results["warm_service_reconciled"] = stats(reconciliations)

print(json.dumps({"workloads": results, "status_before": status, "status_after": end_status,
                  "memory_after_warm": warm_memory,
                  "method": "warm, serial daemon round-trip; picker includes Python/CLI startup and rendering; live updates poll every 5ms; restart includes systemctl overhead and warm OS cache"}, indent=2))
